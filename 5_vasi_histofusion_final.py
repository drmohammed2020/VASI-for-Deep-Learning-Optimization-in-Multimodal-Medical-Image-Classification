class AttentionFusion(nn.Module):
    def __init__(self, in_dim=256, num_features=4):
        super(AttentionFusion, self).__init__()
        self.proj = nn.Linear(in_dim, in_dim)
        self.attn = nn.Linear(in_dim, 1)
        self.num_features = num_features
    def forward(self, features):
        stacked = torch.stack(features, dim=1)  # [B, num_features, in_dim]
        proj = torch.tanh(self.proj(stacked))
        attn_scores = self.attn(proj)
        attn_weights = F.softmax(attn_scores, dim=1)
        fused = torch.sum(attn_weights * stacked, dim=1)
        return fused

class MFF_CNN(nn.Module):
    def __init__(self, pretrained=True):
        super(MFF_CNN, self).__init__()
        resnet = models.resnet50(weights='DEFAULT' if pretrained else None)
        self.layer0 = nn.Sequential(resnet.conv1, resnet.bn1, resnet.relu, resnet.maxpool)
        self.layer1 = resnet.layer1
        self.layer2 = resnet.layer2
        self.layer3 = resnet.layer3
        self.layer4 = resnet.layer4
        self.proj1 = nn.Conv2d(256, 256, kernel_size=1)
        self.proj2 = nn.Conv2d(512, 256, kernel_size=1)
        self.proj3 = nn.Conv2d(1024, 256, kernel_size=1)
        self.proj4 = nn.Conv2d(2048, 256, kernel_size=1)
        self.global_pool = nn.AdaptiveAvgPool2d((1,1))
        self.attn_fusion = AttentionFusion(in_dim=256, num_features=4)

    def forward(self, x):
        x0 = self.layer0(x)
        x1 = self.layer1(x0)
        x2 = self.layer2(x1)
        x3 = self.layer3(x2)
        x4 = self.layer4(x3)
        f1 = self.global_pool(self.proj1(x1)).flatten(1)
        f2 = self.global_pool(self.proj2(x2)).flatten(1)
        f3 = self.global_pool(self.proj3(x3)).flatten(1)
        f4 = self.global_pool(self.proj4(x4)).flatten(1)
        fused_features = self.attn_fusion([f1, f2, f3, f4])
        return fused_features

class QTN_Layer(nn.Module):
    def __init__(self, input_dim=256, output_dim=128):
        super(QTN_Layer, self).__init__()
        self.compress = nn.Sequential(
            nn.Linear(input_dim, 512),
            nn.ReLU(),
            nn.Linear(512, output_dim),
            nn.ReLU()
        )
    def forward(self, x):
        return self.compress(x)

class MFF_HistoNet(nn.Module):
    def __init__(self, num_classes=2, qtn_outdim=128, classifier_hidden=64, dropout=0.4, pretrained_backbone=False):
        super(MFF_HistoNet, self).__init__()
        self.cnn_backbone = MFF_CNN(pretrained=pretrained_backbone)
        self.qtn_layer = QTN_Layer(input_dim=256, output_dim=int(qtn_outdim))
        self.classifier = nn.Sequential(
            nn.Linear(int(qtn_outdim), int(classifier_hidden)),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(int(classifier_hidden), num_classes)
        )
    def forward(self, image):
        cnn_feat = self.cnn_backbone(image)
        qtn_feat = self.qtn_layer(cnn_feat)
        output = self.classifier(qtn_feat)
        return output

