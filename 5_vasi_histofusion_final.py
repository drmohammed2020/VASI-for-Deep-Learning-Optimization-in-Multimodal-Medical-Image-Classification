# Function to register hooks for Grad-CAM
def register_hooks(model, target_layer):
    # Stores the feature maps
    feature_maps = []
    # Stores the gradients of the target output w.r.t. the feature maps
    gradients = []

    def save_feature_maps(module, input, output):
        feature_maps.append(output)

    def save_gradients(module, grad_in, grad_out):
        # grad_out is a tuple, we need the gradient w.r.t. the output
        gradients.append(grad_out[0])

    # Register hooks
    hook_handle_fm = target_layer.register_forward_hook(save_feature_maps)
    hook_handle_grad = target_layer.register_backward_hook(save_gradients)

    return feature_maps, gradients, hook_handle_fm, hook_handle_grad

# Function to generate Grad-CAM heatmap
def generate_grad_cam(image, model, target_layer, target_class=None):
    feature_maps, gradients, hook_fm, hook_grad = register_hooks(model, target_layer)

    # Add batch dimension and move to device
    input_tensor = image.unsqueeze(0).to(device)

    # Forward pass
    output = model(input_tensor)

    # Get the predicted class
    predicted_class = output.argmax(dim=1).item()

    # If target_class is not specified, use the predicted class
    if target_class is None:
        target_class = predicted_class

    # Zero gradients
    model.zero_grad()

    # Backward pass to get gradients w.r.t. the target class output
    target_output = output[0, target_class]
    target_output.backward()

    # Get the feature maps and gradients
    feature_map = feature_maps[0].squeeze(0)
    gradient = gradients[0].squeeze(0)

    # Deregister hooks
    hook_fm.remove()
    hook_grad.remove()

    # Calculate the weights (global average pooling of gradients)
    weights = torch.mean(gradient, dim=(1, 2), keepdim=True)

    # Compute the CAM
    cam = torch.sum(weights * feature_map, dim=0)

    # Apply ReLU to the CAM
    cam = F.relu(cam)

    # Normalize the CAM to be between 0 and 1
    cam = cam / torch.max(cam)

    # Convert CAM to numpy array and resize to input image size
    cam_np = cam.detach().cpu().numpy()
    h, w = image.shape[1:] # Get original image height and width
    cam_resized = cv2.resize(cam_np, (w, h))

    return cam_resized, predicted_class, target_class

# Function to display the image with Grad-CAM heatmap
def display_grad_cam(image, heatmap, title="Grad-CAM"):
    # Convert image tensor to numpy and denormalize/transpose if needed
    # Assuming image is already normalized and in (C, H, W) format
    # Convert to (H, W, C) and denormalize if necessary for display
    image_np = image.permute(1, 2, 0).cpu().numpy()

    # Denormalize the image if it was normalized (e.g., by dividing by 255.0)
    # If simple_normalize divided by 255, we multiply by 255 here
    # If ToTensorV2 normalized to [0, 1], no denormalization needed here for display

    # Ensure image_np is in uint8 for overlay
    # If image_np is float [0, 1], convert to uint8 [0, 255]
    image_np_uint8 = (image_np * 255).astype(np.uint8)


    # Apply heatmap color map
    heatmap_colored = cv2.applyColorMap(np.uint8(255 * heatmap), cv2.COLORMAP_JET)

    # Overlay heatmap on the original image
    # Use cv2.addWeighted for alpha blending
    overlayed_image = cv2.addWeighted(image_np_uint8, 0.6, heatmap_colored, 0.4, 0)

    # Display the images
    fig, axes = plt.subplots(1, 3, figsize=(18, 6)) # Increased figsize


    axes[0].imshow(image_np_uint8)
    axes[0].set_title("Original Image")
    axes[0].axis('off')

    axes[1].imshow(heatmap, cmap='jet')
    axes[1].set_title("Grad-CAM Heatmap")
    axes[1].axis('off')

    axes[2].imshow(overlayed_image)
    axes[2].set_title(title)
    axes[2].axis('off')

    plt.tight_layout()
    plt.show()

