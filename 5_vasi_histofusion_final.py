# ✅ Main Model Combining CNN + QTN (Texture Features Removed)
class MFF_HistoNet(nn.Module):
    # Removed texture_dim as it's no longer used
    def __init__(self, num_classes=2): # Changed num_classes to 2
        super(MFF_HistoNet, self).__init__()
        self.cnn_backbone = MFF_CNN()

        # Total feature dim after CNN MFF is 1024
        # QTN layer compresses from 1024 to 128
        self.qtn_layer = QTN_Layer(input_dim=1024, output_dim=128)

        # Final classifier takes output from QTN layer (128)
        self.classifier = nn.Sequential(
            # Input dimension is now 128 from the QTN output
            nn.Linear(128, 64),
            nn.ReLU(),
            nn.Dropout(0.4),
            nn.Linear(64, num_classes) # num_classes is 2
        )

    def forward(self, image): # Removed texture_features from input
        cnn_feat = self.cnn_backbone(image)
        qtn_feat = self.qtn_layer(cnn_feat)
        # Removed concatenation with texture_features
        output = self.classifier(qtn_feat)
        return output

